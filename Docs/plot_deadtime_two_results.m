%% Compare two dead-time identification results
% The current axis uses the 20 target-current points from identify_dead.c.

current_A = [ ...
    0.05 0.10 0.15 0.20 0.25 0.30 0.35 0.40 0.45 0.50 ...
    0.60 0.70 0.80 0.90 1.00 1.10 1.20 1.30 1.40 1.50];

dead_voltage_result_1_V = [ ...
    0.0783979446 0.0928440690 0.1062120500 0.1144288780 0.1180228590 ...
    0.1210918430 0.1232030390 0.1213740110 0.1160281900 0.1171035770 ...
    0.1073126790 0.1064603330 0.1032989030 0.1165223120 0.1309335230 ...
    0.1534061430 0.1849372390 0.2204387190 0.2649173740 0.3047542570];

dead_voltage_result_2_V = [ ...
    0.08999722278 0.1146392520 0.1335574390 0.1469503640 0.1519996520 ...
    0.14768677900 0.1424975400 0.1328917740 0.1279740330 0.1245332960 ...
    0.11370384700 0.1085379120 0.1065578460 0.1089334490 0.1237363820 ...
    0.14858698800 0.1696553230 0.2043409350 0.2379789350 0.3184723850];

assert(numel(current_A) == numel(dead_voltage_result_1_V));
assert(numel(current_A) == numel(dead_voltage_result_2_V));

difference_V = dead_voltage_result_2_V - dead_voltage_result_1_V;
[max_abs_difference_V, max_difference_idx] = max(abs(difference_V));
rmse_V = sqrt(mean(difference_V.^2));

fig = figure('Color', 'w', 'Position', [100 100 1200 720]);
ax = axes(fig);
hold(ax, 'on');

plot(ax, current_A, dead_voltage_result_1_V, '-o', ...
    'Color', [0.08 0.38 0.72], 'LineWidth', 2.1, ...
    'MarkerSize', 6.5, 'MarkerFaceColor', [0.23 0.62 0.88], ...
    'DisplayName', 'Identification result 1');
plot(ax, current_A, dead_voltage_result_2_V, '-s', ...
    'Color', [0.88 0.30 0.12], 'LineWidth', 2.1, ...
    'MarkerSize', 6.5, 'MarkerFaceColor', [0.96 0.52 0.22], ...
    'DisplayName', 'Identification result 2');

scatter(ax, current_A(max_difference_idx), ...
    dead_voltage_result_1_V(max_difference_idx), 90, ...
    [0.46 0.16 0.64], 'filled', 'HandleVisibility', 'off');
scatter(ax, current_A(max_difference_idx), ...
    dead_voltage_result_2_V(max_difference_idx), 90, ...
    [0.46 0.16 0.64], 'filled', 'HandleVisibility', 'off');
plot(ax, [current_A(max_difference_idx) current_A(max_difference_idx)], ...
    [dead_voltage_result_1_V(max_difference_idx) ...
     dead_voltage_result_2_V(max_difference_idx)], ':', ...
    'Color', [0.46 0.16 0.64], 'LineWidth', 1.5, ...
    'DisplayName', 'Largest difference');

hold(ax, 'off');
grid(ax, 'on');
ax.XMinorGrid = 'on';
ax.YMinorGrid = 'on';
ax.GridAlpha = 0.22;
ax.Box = 'on';
ax.FontSize = 12;
ax.FontName = 'Microsoft YaHei';
ax.TickDir = 'out';

title(ax, 'Comparison of two dead-time identification results - latest dataset');
subtitle(ax, 'Current coordinates use the identification target-current points');
xlabel(ax, 'Identified current magnitude |I| (A)');
ylabel(ax, 'Dead-time compensation voltage V_{dead} (V)');
legend(ax, 'Location', 'northwest', 'Box', 'off');
xlim(ax, [0 1.55]);
y_axis_max = ceil(max([dead_voltage_result_1_V dead_voltage_result_2_V]) / 0.05) * 0.05;
ylim(ax, [0 y_axis_max]);

summary_text = sprintf(['RMSE between results = %.4f V\n' ...
    'Max difference = %.4f V at %.2f A\n' ...
    'Result 2 - Result 1 = %+.4f V'], ...
    rmse_V, max_abs_difference_V, current_A(max_difference_idx), ...
    difference_V(max_difference_idx));
text(ax, 0.98, 0.05, summary_text, 'Units', 'normalized', ...
    'HorizontalAlignment', 'right', 'VerticalAlignment', 'bottom', ...
    'FontName', 'Consolas', 'FontSize', 11, ...
    'BackgroundColor', 'w', 'EdgeColor', [0.75 0.75 0.75], ...
    'Margin', 7);

script_dir = fileparts(mfilename('fullpath'));
output_path = fullfile(script_dir, 'deadtime_identification_two_results_latest.png');
exportgraphics(ax, output_path, 'Resolution', 220);

fprintf('Output: %s\n', output_path);
fprintf('RMSE between results: %.7f V\n', rmse_V);
fprintf('Max absolute difference: %.7f V at %.2f A\n', ...
    max_abs_difference_V, current_A(max_difference_idx));

%% Dead-time identification: current-voltage nonlinearity
% Voltage samples were read from g_identify.res.dead_lut_V in the debugger.
% Current values are the identification targets defined in identify_dead.c.

current_A = [ ...
    0.05 0.10 0.15 0.20 0.25 0.30 0.35 0.40 0.45 0.50 ...
    0.60 0.70 0.80 0.90 1.00 1.10 1.20 1.30 1.40 1.50];

dead_voltage_V = [ ...
    0.0227416158 0.0552063286 0.0784576237 0.0956031084 0.111355484 ...
    0.1288439040 0.1119611260 0.1143790480 0.0174535513 0.0107029676 ...
    0.0134397745 0.0119564533 0.0107238293 0.0149629116 0.0184657574 ...
    0.0328142643 0.0522508621 0.0809366703 0.1123423580 0.177030563];

assert(numel(current_A) == numel(dead_voltage_V), ...
    'Current and voltage arrays must have the same number of points.');

fit_coeff = polyfit(current_A, dead_voltage_V, 1);
fit_at_samples = polyval(fit_coeff, current_A);
residual_V = dead_voltage_V - fit_at_samples;
r_squared = 1 - sum(residual_V.^2) / ...
    sum((dead_voltage_V - mean(dead_voltage_V)).^2);
[max_abs_residual_V, max_residual_idx] = max(abs(residual_V));
[largest_drop_V, largest_drop_idx] = min(diff(dead_voltage_V));
largest_drop_end_idx = largest_drop_idx + 1;

fit_current_A = linspace(min(current_A), max(current_A), 400);
fit_voltage_V = polyval(fit_coeff, fit_current_A);

fig = figure('Color', 'w', 'Position', [100 100 1200 720]);
ax = axes(fig);
hold(ax, 'on');

for idx = 1:numel(current_A)
    plot(ax, [current_A(idx) current_A(idx)], ...
        [fit_at_samples(idx) dead_voltage_V(idx)], ':', ...
        'Color', [0.72 0.72 0.72], 'LineWidth', 0.9, ...
        'HandleVisibility', 'off');
end

plot(ax, fit_current_A, fit_voltage_V, '--', ...
    'Color', [0.90 0.33 0.12], 'LineWidth', 1.8, ...
    'DisplayName', 'Linear reference');
plot(ax, current_A, dead_voltage_V, '-o', ...
    'Color', [0.10 0.38 0.72], 'LineWidth', 2.0, ...
    'MarkerSize', 6.5, 'MarkerFaceColor', [0.20 0.58 0.88], ...
    'DisplayName', 'Identified dead-time voltage');

scatter(ax, current_A(max_residual_idx), dead_voltage_V(max_residual_idx), ...
    95, [0.80 0.10 0.15], 'filled', 'DisplayName', 'Largest deviation');
scatter(ax, current_A(largest_drop_end_idx), dead_voltage_V(largest_drop_end_idx), ...
    105, [0.62 0.12 0.70], 'd', 'filled', ...
    'DisplayName', 'Largest voltage drop');

hold(ax, 'off');
grid(ax, 'on');
ax.XMinorGrid = 'on';
ax.YMinorGrid = 'on';
ax.GridAlpha = 0.22;
ax.Box = 'on';
ax.FontSize = 12;
ax.FontName = 'Microsoft YaHei';
ax.TickDir = 'out';

title(ax, 'Dead-time identification current-voltage characteristic - dataset 2');
subtitle(ax, 'Vertical dotted lines show deviation from a global linear fit');
xlabel(ax, 'Identified current magnitude |I| (A)');
ylabel(ax, 'Dead-time compensation voltage V_{dead} (V)');
legend(ax, 'Location', 'northwest', 'Box', 'off');
xlim(ax, [0 1.55]);
y_axis_max = max(0.05, ceil(max(dead_voltage_V) / 0.05) * 0.05);
ylim(ax, [0 y_axis_max]);

summary_text = sprintf(['Linear fit: V = %.4f I + %.4f\n' ...
    'R^2 = %.4f\nMax |residual| = %.4f V at %.2f A\n' ...
    'Largest step drop = %.4f V at %.2f -> %.2f A'], ...
    fit_coeff(1), fit_coeff(2), r_squared, max_abs_residual_V, ...
    current_A(max_residual_idx), largest_drop_V, ...
    current_A(largest_drop_idx), current_A(largest_drop_end_idx));
text(ax, 0.98, 0.05, summary_text, 'Units', 'normalized', ...
    'HorizontalAlignment', 'right', 'VerticalAlignment', 'bottom', ...
    'FontName', 'Consolas', 'FontSize', 11, ...
    'BackgroundColor', 'w', 'EdgeColor', [0.75 0.75 0.75], ...
    'Margin', 7);

script_dir = fileparts(mfilename('fullpath'));
output_path = fullfile(script_dir, 'deadtime_current_voltage_nonlinearity_run2.png');
exportgraphics(ax, output_path, 'Resolution', 220);

fprintf('Output: %s\n', output_path);
fprintf('Linear fit: V = %.7f * I + %.7f, R^2 = %.6f\n', ...
    fit_coeff(1), fit_coeff(2), r_squared);
fprintf('Max absolute residual: %.7f V at %.2f A\n', ...
    max_abs_residual_V, current_A(max_residual_idx));
fprintf('Largest step drop: %.7f V from %.2f A to %.2f A\n', ...
    largest_drop_V, current_A(largest_drop_idx), ...
    current_A(largest_drop_end_idx));
